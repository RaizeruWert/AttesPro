from django.core.management.base import BaseCommand
from core.models import ChecklistItem
class Command(BaseCommand):
    help = "Добавляет стартовый перечень документов АттестПро."
    def handle(self, *args, **kwargs):
        rows = [
            ("Заявление на аттестацию", "Форма и адресат уточняются по действующей процедуре.", "common", True, 1),
            ("Документ об образовании", "Копия документа об образовании и квалификации.", "common", True, 2),
            ("Сведения о трудовой деятельности", "Стаж и сведения о работе в выбранной должности.", "common", True, 3),
            ("Документы о повышении квалификации", "Сертификаты, удостоверения и иные подтверждения.", "common", True, 4),
            ("Самоанализ / аналитический материал", "Материалы по выбранной должности и цели аттестации.", "common", True, 5),
            ("Материалы о результатах обучения", "Результаты и динамика обучающихся; состав подтверждений уточняется по требованиям.", "pedagogical", True, 10),
            ("Методические разработки", "Разработки уроков, программ, методических материалов.", "pedagogical", False, 11),
            ("Сведения о педагогическом опыте", "Обобщение опыта, открытые занятия, публикации и выступления.", "pedagogical", False, 12),
            ("Планирование и результаты работы подразделения", "Материалы по управленческой деятельности.", "management", True, 20),
            ("Документы о качестве управления", "Аналитические справки и подтверждения результатов управления.", "management", False, 21),
            ("Работа с коллективом", "Материалы о развитии педагогического коллектива.", "management", False, 22),
        ]
        for title, description, scope, required, order in rows:
            ChecklistItem.objects.get_or_create(title=title, scope=scope, defaults={
                "description": description, "required": required, "sort_order": order, "active": True
            })
        self.stdout.write(self.style.SUCCESS("Стартовый список документов добавлен. Его можно изменить в админ-панели."))
